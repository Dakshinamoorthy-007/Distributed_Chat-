import { WebSocket } from 'ws';

const baseUrl = process.env.CHAT_BASE_URL ?? 'http://localhost:80';
const runId = Date.now().toString(36);
const users = [`itest-alice-${runId}`, `itest-bob-${runId}`, `itest-charlie-${runId}`];
const [alice, bob, charlie] = users;

async function request(path, init) {
  const response = await fetch(`${baseUrl}${path}`, {
    ...init,
    headers: { 'Content-Type': 'application/json', Accept: 'application/json', ...(init?.headers ?? {}) }
  });
  const text = await response.text();
  let body = text;
  try { body = text ? JSON.parse(text) : null; } catch { /* plain body */ }
  if (!response.ok) throw new Error(`${init?.method ?? 'GET'} ${path} -> HTTP ${response.status}: ${text}`);
  return body;
}

function waitForSocket(userId, conversationId) {
  return new Promise((resolve, reject) => {
    const url = baseUrl.replace(/^http/, 'ws') + `/ws/chat?userId=${encodeURIComponent(userId)}&conversationId=${encodeURIComponent(conversationId)}`;
    const socket = new WebSocket(url);
    const timeout = setTimeout(() => {
      socket.close();
      reject(new Error(`Timed out waiting for CONNECTED for ${userId}`));
    }, 5000);
    socket.on('message', (raw) => {
      const event = JSON.parse(raw.toString());
      if (event.type === 'CONNECTED') {
        clearTimeout(timeout);
        resolve({ socket, connected: event });
      }
    });
    socket.on('error', (error) => {
      clearTimeout(timeout);
      reject(error);
    });
  });
}

function waitForRejected(userId, conversationId) {
  return new Promise((resolve, reject) => {
    const url = baseUrl.replace(/^http/, 'ws') + `/ws/chat?userId=${encodeURIComponent(userId)}&conversationId=${encodeURIComponent(conversationId)}`;
    const socket = new WebSocket(url);
    const timeout = setTimeout(() => { socket.close(); reject(new Error('Timed out waiting for membership rejection')); }, 5000);
    socket.on('close', (code, reason) => {
      clearTimeout(timeout);
      resolve({ code, reason: reason.toString() });
    });
    socket.on('error', () => { /* close event carries the policy violation */ });
  });
}

async function waitForPresence(userId, expected) {
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const result = await request(`/api/presence/${encodeURIComponent(userId)}`);
    if (result.online === expected) return result;
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`Presence for ${userId} did not become ${expected}`);
}

async function main() {
  console.log(`Testing through ${baseUrl}`);

  const conversation = await request('/api/conversations', {
    method: 'POST',
    body: JSON.stringify({ name: `Integration ${runId}`, type: 'GROUP', userIds: [alice, bob] })
  });
  console.log(`PASS create GROUP conversation ${conversation.id}`);

  await request(`/api/conversations/${conversation.id}/members`, {
    method: 'POST', body: JSON.stringify({ userId: charlie })
  });
  console.log('PASS add conversation member');

  const members = await request(`/api/conversations/${conversation.id}/members`);
  if (JSON.stringify([...members].sort()) !== JSON.stringify([...users].sort())) throw new Error(`Members mismatch: ${JSON.stringify(members)}`);
  console.log('PASS get conversation members');

  const aliceConversations = await request(`/api/conversations?userId=${encodeURIComponent(alice)}`);
  if (!aliceConversations.some((item) => item.id === conversation.id)) throw new Error('Created conversation missing from user conversation list');
  console.log('PASS list user conversations');

  const outsider = await waitForRejected(`itest-outsider-${runId}`, conversation.id);
  if (outsider.code !== 1008) throw new Error(`Expected membership rejection 1008, got ${outsider.code} (${outsider.reason})`);
  console.log('PASS membership validation rejects outsider');

  const sockets = await Promise.all(users.map((userId) => waitForSocket(userId, conversation.id)));
  const serverIds = new Set(sockets.map((item) => item.connected.serverId));
  console.log(`PASS WebSocket CONNECTED for 3 users (${[...serverIds].join(', ')})`);
  if (serverIds.size < 2) throw new Error(`Expected clients to reach both backend instances through Nginx, got: ${[...serverIds].join(', ')}`);

  await waitForPresence(alice, true);
  console.log('PASS online presence');

  const content = `integration-message-${runId}`;
  const aliceSocket = sockets[0].socket;
  // The ID is generated by PostgreSQL/backend, so capture the actual MESSAGE from Alice first.
  const received = sockets.map(() => []);
  const handlers = sockets.map((item, index) => {
    const handler = (raw) => {
      const event = JSON.parse(raw.toString());
      if (event.type === 'MESSAGE' && event.message?.content === content) received[index].push(event.message);
    };
    item.socket.on('message', handler);
    return handler;
  });

  aliceSocket.send(JSON.stringify({ conversationId: conversation.id, content }));
  for (let attempt = 0; attempt < 50 && received.some((items) => !items.length); attempt += 1) {
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  for (const [index, items] of received.entries()) {
    if (items.length !== 1) throw new Error(`Expected exactly one delivery for user index ${index}, got ${items.length}`);
  }
  const message = received[0][0];
  for (const item of received) if (item[0].id !== message.id) throw new Error('Message IDs differ across recipients');
  sockets.forEach((item, index) => item.socket.off('message', handlers[index]));
  console.log('PASS real-time message fan-out through WebSocket/Redis');

  const history = await request(`/api/conversations/${conversation.id}/messages`);
  if (!history.some((item) => item.id === message.id && item.content === content)) throw new Error('Sent message missing from history');
  console.log('PASS persisted message appears in history');

  sockets.forEach((item) => item.socket.close(1000, 'integration test complete'));
  await waitForPresence(alice, false);
  console.log('PASS offline presence after disconnect');

  console.log('ALL LIVE INTEGRATION TESTS PASSED');
}

try {
  await main();
} catch (error) {
  console.error(`FAIL ${error.message}`);
  process.exitCode = 1;
}
